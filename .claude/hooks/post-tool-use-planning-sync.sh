#!/bin/bash
# =============================================================================
# .claude/hooks/post-tool-use-planning-sync.sh
# Auto-sync backbone/planning/STATE.md from backbone/3-TASKS.md
# =============================================================================
# Trigger: PostToolUse on Write/Edit to backbone/*.md
# Action: Parse 3-TASKS.md, regenerate STATE.md sections
# Debounce: Only sync if content hash changed
# Silent fail: Yes
# =============================================================================

set -e

PROJECT_ROOT="$(git rev-parse --show-toplevel 2>/dev/null || true)"
if [[ -z "$PROJECT_ROOT" ]]; then
  exit 0
fi

TASKS_FILE="$PROJECT_ROOT/backbone/3-TASKS.md"
STATE_FILE="$PROJECT_ROOT/backbone/planning/STATE.md"
HASH_FILE="/tmp/backbone-tasks-hash-$(echo "$PROJECT_ROOT" | tr '/' '_')"

# ── Only proceed if 3-TASKS.md exists ──────────────────────────────────────
if [[ ! -f "$TASKS_FILE" ]]; then
  exit 0
fi

# ── Debounce: check if file changed ────────────────────────────────────────
CURRENT_HASH=$(md5 -q "$TASKS_FILE" 2>/dev/null || md5sum "$TASKS_FILE" 2>/dev/null | cut -d' ' -f1 || true)
if [[ -f "$HASH_FILE" ]]; then
  LAST_HASH=$(cat "$HASH_FILE" 2>/dev/null || true)
  if [[ "$CURRENT_HASH" == "$LAST_HASH" ]]; then
    exit 0
  fi
fi

# Save current hash
echo "$CURRENT_HASH" > "$HASH_FILE"

# ── Parse 3-TASKS.md and generate STATE.md ─────────────────────────────────
TMP_SCRIPT=$(mktemp)
cat > "$TMP_SCRIPT" << 'PYTHON_EOF'
import re
import sys
from datetime import datetime

tasks_file = sys.argv[1]
state_file = sys.argv[2]

try:
    with open(tasks_file, 'r', encoding='utf-8') as f:
        content = f.read()
except:
    sys.exit(0)

# Extract WIP tasks (blockers)
blockers = []
for match in re.finditer(r'^\|\s*\*\*(.+?)\*\*\s*\|\s*\[WIP\]\s*\|', content, re.MULTILINE):
    blockers.append(f"Milestone: {match.group(1).strip()}")
for match in re.finditer(r'^\s*-\s*\[WIP\]\s*(.+)$', content, re.MULTILINE):
    task = match.group(1).strip()
    if not task.startswith('`[') and 'do NOT start' not in task and 'In progress' not in task:
        blockers.append(task)

# Extract milestones
milestones = []
for match in re.finditer(r'^\|\s*\*\*(.+?)\*\*\s*\|\s*\[(\w+)\]\s*\|\s*(\d+)%\s*\|\s*(.+?)\s*\|', content, re.MULTILINE):
    name = match.group(1).strip()
    status = match.group(2).strip()
    progress = match.group(3).strip()
    desc = match.group(4).strip()
    milestones.append((name, status, progress, desc))

# Build sections
blockers_content = ""
if blockers:
    for b in blockers:
        blockers_content += f"- 🔄 {b}\n"
else:
    blockers_content = "- ✅ No active blockers\n"

milestones_content = ""
if milestones:
    for name, status, progress, desc in milestones:
        icon = "✅" if status == "x" else "🔄" if status.lower() == "wip" else "⬜"
        milestones_content += f"| {icon} | {name} | {progress}% | {desc} |\n"
else:
    milestones_content = "No milestones tracked.\n"

# Session log
existing_sessions = []
try:
    with open(state_file, 'r', encoding='utf-8') as f:
        existing = f.read()
    session_match = re.search(r'<!-- AUTO_SESSION_LOG_START -->(.*?)<!-- AUTO_SESSION_LOG_END -->', existing, re.DOTALL)
    if session_match:
        session_text = session_match.group(1).strip()
        for line in session_text.split('\n'):
            line = line.strip()
            if line.startswith('- ') and 'State synced' not in line:
                existing_sessions.append(line)
except:
    pass

timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
session_entry = f"- {timestamp} — State synced from 3-TASKS.md"
all_sessions = (existing_sessions + [session_entry])[-20:]
session_content = '\n'.join(all_sessions) + '\n'

# Generate STATE.md
state_content = f"""# State — Auto-synced from backbone/3-TASKS.md

> **Do NOT edit this file manually.**
> It is automatically regenerated when backbone/3-TASKS.md is modified.
> Run `/backbone:health` to force a sync.

---

## Current Blockers

<!-- AUTO_BLOCKERS_START -->
{blockers_content}<!-- AUTO_BLOCKERS_END -->

---

## Milestone Progress

<!-- AUTO_MILESTONES_START -->
| Status | Milestone | Progress | Description |
|--------|-----------|----------|-------------|
{milestones_content}<!-- AUTO_MILESTONES_END -->

---

## Quick Tasks Completed

<!-- AUTO_QUICK_TASKS_START -->
- No quick tasks recorded yet.
<!-- AUTO_QUICK_TASKS_END -->

---

## Session Log

<!-- AUTO_SESSION_LOG_START -->
{session_content}<!-- AUTO_SESSION_LOG_END -->

---

*Last synced: <!-- AUTO_TIMESTAMP -->{timestamp}<!-- AUTO_TIMESTAMP_END -->*
"""

try:
    with open(state_file, 'w', encoding='utf-8') as f:
        f.write(state_content)
except:
    pass
PYTHON_EOF

python3 "$TMP_SCRIPT" "$TASKS_FILE" "$STATE_FILE"
rm -f "$TMP_SCRIPT"
